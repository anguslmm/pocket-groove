// gen_tables: regenerates the constant DSP lookup tables of the portable core
// from their reference formulas, so the firmware keeps them in flash instead
// of computing them into RAM at init().
//
//   cmake --build build/host --target gen_tables
//   build/host/gen_tables lib/pg/src          (run from the project root)
//
// Writes (and overwrites):
//   lib/pg/src/pg/lead/lead_tables_data.cpp   lead wavetables, 44.1 + 32 kHz sets
//   lib/pg/src/pg/bass/bass_tables_data.cpp   bass sine + BLEP residual tables
// The formulas are lead/lead_tables_ref.cpp and bass/bass_tables_ref.cpp;
// host/tests/test_lead_tables.cpp and test_bass_tables.cpp fail whenever the
// checked-in data no longer equals them. Output is deterministic (exact hex
// floats), so regenerating with an unchanged formula gives identical files.
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#include "pg/bass/bass_math.h"
#include "pg/lead/lead_tables.h"

namespace {

std::string hexf(float f) {
  char b[64];
  std::snprintf(b, sizeof b, "%a", double(f));
  std::string s(b);
  if (s.find('p') == std::string::npos) s += "p+0";
  return s + "f";
}

bool writeFile(const std::string& path, const std::string& text) {
  FILE* f = std::fopen(path.c_str(), "wb");
  if (!f) { std::fprintf(stderr, "gen_tables: cannot write %s\n", path.c_str()); return false; }
  std::fwrite(text.data(), 1, text.size(), f);
  std::fclose(f);
  std::printf("  wrote %s (%zu bytes)\n", path.c_str(), text.size());
  return true;
}

const char* kBanner =
    "// GENERATED by tools/gen/gen_tables.cpp from the reference formula in %s.\n"
    "// Do not edit. Regenerate: cmake --build build/host --target gen_tables &&\n"
    "// build/host/gen_tables lib/pg/src   (host/tests/test_%s_tables.cpp checks it)\n";

// ------------------------------------------------------------------- lead --
struct LeadSet {
  float fs;
  const char* name;
  std::vector<int16_t> pool;
  pg::lead::Tables t;
};

std::string genLead() {
  using namespace pg::lead;
  LeadSet sets[2] = {{44100.0f, "kTables44k", {}, {}}, {32000.0f, "kTables32k", {}, {}}};
  for (LeadSet& s : sets) {
    s.pool.assign(kRefPoolSize, 0);
    buildTablesReference(s.fs, s.pool.data(), s.t);
  }
  // Unique tables, in order of first use: 44.1 kHz set first, then whatever
  // the 32 kHz set does not share with it (saw/triangle mips whose harmonic
  // count depends on Nyquist).
  std::vector<int16_t> data;
  std::vector<std::vector<int16_t>> uniq;
  std::vector<size_t> uniqOff;
  auto offsetOf = [&](const Tab& tab) -> size_t {
    const size_t n = (size_t(1) << (32 - tab.shift)) + 1;
    std::vector<int16_t> v(tab.d, tab.d + n);
    for (size_t i = 0; i < uniq.size(); ++i)
      if (uniq[i] == v) return uniqOff[i];
    uniq.push_back(v);
    uniqOff.push_back(data.size());
    data.insert(data.end(), v.begin(), v.end());
    return uniqOff.back();
  };
  auto tabInit = [&](const Tab& tab) {
    char b[160];
    std::snprintf(b, sizeof b, "{kWave + %zu, %uu, 0x%xu, %s}", offsetOf(tab), unsigned(tab.shift), unsigned(tab.mask),
                  hexf(tab.fscale).c_str());
    return std::string(b);
  };
  std::string defs;
  for (const LeadSet& s : sets) {
    const Tables& t = s.t;
    std::string d = "const Tables " + std::string(s.name) + " = {\n    // saw\n    {";
    for (int b = 0; b < kNumBands; ++b) d += (b ? ",\n     " : "") + tabInit(t.saw[b]);
    d += "},\n    // triangle\n    {";
    for (int b = 0; b < kNumBands; ++b) d += (b ? ",\n     " : "") + tabInit(t.tri[b]);
    d += "},\n    // organ [registration][mip]\n    {";
    for (int r = 0; r < kOrgRegs; ++r) {
      d += r ? ",\n     {" : "{";
      for (int l = 0; l < kOrgLevels; ++l) d += (l ? ", " : "") + tabInit(t.organ[r][l]);
      d += "}";
    }
    d += "},\n    // sine\n    " + tabInit(t.sine) + ",\n";
    d += "    " + hexf(t.organPitch1) + ", " + hexf(t.organPitch2) + ",   // organPitch1, organPitch2\n";
    d += "    " + hexf(t.sampleRate) + "};\n\n";
    defs += d;
  }
  char head[512];
  std::snprintf(head, sizeof head, kBanner, "lib/pg/src/pg/lead/lead_tables_ref.cpp", "lead");
  std::string out = head;
  char line[256];
  std::snprintf(line, sizeof line,
                "// %zu int16 samples = %zu bytes of flash (.rodata); %zu unique tables.\n"
                "#include \"../table_attr.h\"\n#include \"lead_tables.h\"\n\n"
                "namespace pg {\nnamespace lead {\nnamespace {\n\n",
                data.size(), 2 * data.size(), uniq.size());
  out += line;
  std::snprintf(line, sizeof line, "PG_TABLE_ATTR const int16_t kWave[%zu] = {\n", data.size());
  out += line;
  for (size_t i = 0; i < data.size(); ++i) {
    if (i % 12 == 0) out += "    ";
    std::snprintf(line, sizeof line, "%d,", int(data[i]));
    out += line;
    out += (i % 12 == 11 || i + 1 == data.size()) ? "\n" : " ";
  }
  out += "};\n\n}  // namespace\n\n" + defs + "}  // namespace lead\n}  // namespace pg\n";
  return out;
}

// ------------------------------------------------------------------- bass --
std::string floatArray(const char* decl, const float* v, int n) {
  std::string out = std::string("PG_TABLE_ATTR ") + decl + " = {\n";
  char b[64];
  for (int i = 0; i < n; ++i) {
    if (i % 6 == 0) out += "    ";
    std::snprintf(b, sizeof b, "%s,", hexf(v[i]).c_str());
    out += b;
    out += (i % 6 == 5 || i + 1 == n) ? "\n" : " ";
  }
  return out + "};\n";
}

std::string genBass() {
  using namespace pg::bass;
  static float sine[kSineSize + 1], blep[(kBlepPhases + 2) * kBlepTaps];
  buildTablesReference(sine, blep);
  char head[512];
  std::snprintf(head, sizeof head, kBanner, "lib/pg/src/pg/bass/bass_tables_ref.cpp", "bass");
  std::string out = head;
  out += "#include \"../table_attr.h\"\n#include \"bass_math.h\"\n\nnamespace pg {\nnamespace bass {\n\n";
  out += "// sin(2 pi i / 512), i = 0..512 (guard entry = 0)\n";
  out += floatArray("const float gSine[kSineSize + 1]", sine, kSineSize + 1);
  out += "\n// BLEP residuals: (kBlepPhases + 2) rows of kBlepTaps (last row = guard)\n";
  out += floatArray("const float gBlep[(kBlepPhases + 2) * kBlepTaps]", blep, (kBlepPhases + 2) * kBlepTaps);
  out += "\n}  // namespace bass\n}  // namespace pg\n";
  return out;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 2) {
    std::fprintf(stderr, "usage: gen_tables LIB_SRC_DIR   (e.g. lib/pg/src)\n");
    return 2;
  }
  const std::string root = argv[1];
  bool ok = writeFile(root + "/pg/lead/lead_tables_data.cpp", genLead());
  ok = writeFile(root + "/pg/bass/bass_tables_data.cpp", genBass()) && ok;
  return ok ? 0 : 1;
}
