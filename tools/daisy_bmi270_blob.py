#!/usr/bin/env python3
"""Extracts Bosch's BMI270 configuration file for the Daisy firmware (stage 1 tilt).

    python3 tools/daisy_bmi270_blob.py BMI270_SensorAPI/bmi270.c daisy/vendor

Writes daisy/vendor/bmi270_config.inc (the 8192 bytes of bmi270_config_file[] as a C
initializer list) and daisy/vendor/BMI270_LICENSE (the file's BSD-3-Clause notice,
which a binary distribution must reproduce). tools/daisy-setup.sh runs it on a clone
of github.com/boschsensortec/BMI270_SensorAPI at the commit in daisy/libdaisy.lock.
"""
import os
import re
import sys


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    src = open(argv[1], encoding="utf-8", errors="replace").read()
    i = src.index("bmi270_config_file[]")
    j = src.index("{", i)
    k = src.index("}", j)
    data = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", src[j:k])]
    if len(data) != 8192:
        print("daisy_bmi270_blob: expected 8192 bytes, found %d" % len(data))
        return 1
    notice = src[:src.index("*/") + 2] if src.lstrip().startswith("/**") else ""
    os.makedirs(argv[2], exist_ok=True)
    with open(os.path.join(argv[2], "bmi270_config.inc"), "w") as f:
        f.write("// Bosch Sensortec BMI270_SensorAPI bmi270.c bmi270_config_file[] (BSD-3-Clause,\n")
        f.write("// BMI270_LICENSE next to this file). Generated by tools/daisy_bmi270_blob.py.\n")
        for n in range(0, len(data), 16):
            f.write("    " + ", ".join("0x%02x" % b for b in data[n:n + 16]) + ",\n")
    with open(os.path.join(argv[2], "BMI270_LICENSE"), "w") as f:
        f.write(notice + "\n")
    print("daisy_bmi270_blob: 8192 bytes -> %s" % os.path.join(argv[2], "bmi270_config.inc"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
